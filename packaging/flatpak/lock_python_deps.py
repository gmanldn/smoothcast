#!/usr/bin/env python3
"""Regenerate the Flatpak's pinned Python dependency module (#263).

Resolves pyproject's runtime dependencies (plus the setuptools/wheel build
backend) to exact wheels for the GNOME SDK's CPython on x86_64, using pip's
own resolver in --dry-run mode: nothing is installed or executed. Writes
python3-deps.json (a flatpak-builder module whose every source carries a
sha256) and requirements.lock.txt (the same pins, human-readable).

    python3 packaging/flatpak/lock_python_deps.py

Run it after changing [project].dependencies, then rebuild in CI.
"""
from __future__ import annotations

import json
from pathlib import Path
import subprocess
import sys
import tempfile
import tomllib

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PYTHON = "3.14"  # CPython in org.gnome.Sdk//51 (CI-probed 3.14.9)
ABI = "cp" + PYTHON.replace(".", "")
PLATFORMS = ("manylinux_2_28_x86_64", "manylinux_2_17_x86_64", "manylinux2014_x86_64", "any")
BUILD_BACKEND = ("setuptools", "wheel")


def resolve(requirements: list[str]) -> list[dict]:
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        cmd = [sys.executable, "-m", "pip", "install", "--dry-run", "--quiet",
               "--ignore-installed", "--only-binary=:all:", "--report", str(report),
               "--python-version", PYTHON, "--implementation", "cp",
               "--abi", ABI, "--abi", "abi3", "--abi", "none",
               "--target", str(Path(tmp) / "unused")]
        for platform in PLATFORMS:
            cmd += ["--platform", platform]
        subprocess.run(cmd + requirements, check=True)
        return json.loads(report.read_text(encoding="utf-8"))["install"]


def main() -> int:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    items = resolve(list(project["dependencies"]) + list(BUILD_BACKEND))
    pins, sources = [], []
    for item in sorted(items, key=lambda i: i["metadata"]["name"].lower()):
        info = item["download_info"]
        sha = info["archive_info"]["hashes"]["sha256"]
        pins.append(f"{item['metadata']['name']}=={item['metadata']['version']} --hash=sha256:{sha}")
        sources.append({"type": "file", "url": info["url"], "sha256": sha})
    names = " ".join(p.split("==")[0] for p in pins)
    module = {
        "name": "python3-deps",
        "buildsystem": "simple",
        "build-commands": [
            "pip3 install --verbose --exists-action=i --no-index --find-links=\"file://${PWD}\" "
            f"--prefix=${{FLATPAK_DEST}} --no-build-isolation {names}"
        ],
        "sources": sources,
    }
    (HERE / "python3-deps.json").write_text(json.dumps(module, indent=2) + "\n", encoding="utf-8")
    (HERE / "requirements.lock.txt").write_text(
        f"# Generated by lock_python_deps.py for CPython {PYTHON} x86_64; do not edit.\n"
        + "\n".join(pins) + "\n", encoding="utf-8")
    print(f"locked {len(pins)} wheels")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
