"""Extract embedded MKV font attachments for libass subtitle styling.

Matroska containers can carry TrueType/OpenType fonts referenced by ASS/SSA
subtitle styles. FFmpeg's ``subtitles`` filter can load them from a private
directory, so the intended typesetting is preserved without installing
anything into the user's font collection.

Extraction is bounded and validated: only font streams are considered, the
destination name is generated by us (never taken from the container), files
are size-capped and checked for a font signature, and the directory stays in
the caller's private cache.
"""

from __future__ import annotations

import json
import pathlib
import subprocess
from dataclasses import dataclass

import cache_privacy
import media_tools

FONT_EXTENSIONS = frozenset({".ttf", ".otf", ".ttc", ".otc"})
FONT_MIME_TYPES = {
    "application/x-truetype-font": ".ttf",
    "application/x-font-ttf": ".ttf",
    "font/ttf": ".ttf",
    "application/x-font-opentype": ".otf",
    "application/vnd.ms-opentype": ".otf",
    "font/otf": ".otf",
    "application/x-font-ttc": ".ttc",
    "font/collection": ".ttc",
}
MAX_FONT_BYTES = 16 * 1024 * 1024
MAX_FONTS = 16
_FONT_MAGIC = (b"\x00\x01\x00\x00", b"OTTO", b"ttcf", b"true", b"typ1")


@dataclass(frozen=True)
class FontAttachment:
    """A font attachment advertised by the container."""

    index: int
    ordinal: int
    filename: str
    mimetype: str
    suffix: str


def _suffix_for(filename: str, mimetype: str) -> str | None:
    suffix = pathlib.PurePosixPath(filename.replace("\\", "/")).suffix.lower()
    if suffix in FONT_EXTENSIONS:
        return suffix
    return FONT_MIME_TYPES.get(mimetype.lower())


def list_fonts(path: pathlib.Path) -> list[FontAttachment]:
    """Return the font attachments advertised by *path*, in stream order.

    Attachments are identified by ``codec_type`` plus a font filename suffix
    or MIME type. Non-font attachments are ignored. A failed or malformed
    probe yields no fonts instead of breaking the cast.
    """
    try:
        result = subprocess.run(
            [
                media_tools.resolve_media_tool("ffprobe"), "-v", "error",
                "-show_entries", "stream=index,codec_type:stream_tags=filename,mimetype",
                "-of", "json", str(path),
            ],
            capture_output=True, text=True, timeout=30, check=False,
        )
    except Exception:  # noqa: BLE001 - a probe failure must never break a cast
        return []
    if result.returncode != 0:
        return []
    try:
        streams = json.loads(result.stdout or "{}").get("streams", [])
    except (TypeError, ValueError):
        return []
    fonts: list[FontAttachment] = []
    ordinal = 0
    for stream in streams:
        if not isinstance(stream, dict) or stream.get("codec_type") != "attachment":
            continue
        tags = stream.get("tags") if isinstance(stream.get("tags"), dict) else {}
        filename = str(tags.get("filename", ""))
        mimetype = str(tags.get("mimetype", ""))
        suffix = _suffix_for(filename, mimetype)
        index = stream.get("index")
        if suffix is not None and isinstance(index, int) and index >= 0:
            fonts.append(FontAttachment(index, ordinal, filename, mimetype, suffix))
        ordinal += 1
        if len(fonts) >= MAX_FONTS:
            break
    return fonts


def _has_font_magic(path: pathlib.Path) -> bool:
    try:
        with path.open("rb") as handle:
            header = handle.read(4)
    except OSError:
        return False
    return header in _FONT_MAGIC


def _extract_one(source: pathlib.Path, attachment: FontAttachment, destination: pathlib.Path) -> bool:
    """Extract one attachment, returning True only for a valid bounded font."""
    try:
        result = subprocess.run(
            [
                media_tools.resolve_media_tool("ffmpeg"), "-hide_banner", "-loglevel", "error", "-nostdin", "-y",
                "-dump_attachment:t:" + str(attachment.ordinal), str(destination),
                "-i", str(source), "-map", "0", "-c", "copy", "-f", "null", "-",
            ],
            capture_output=True, text=True, timeout=60, check=False,
        )
    except Exception:  # noqa: BLE001 - a failed dump must never break a cast
        destination.unlink(missing_ok=True)
        return False
    try:
        size = destination.stat().st_size
    except OSError:
        return False
    if result.returncode != 0 or size <= 0 or size > MAX_FONT_BYTES or not _has_font_magic(destination):
        destination.unlink(missing_ok=True)
        return False
    return True


def prepare_fonts(source: pathlib.Path, parent: pathlib.Path, generation: str) -> pathlib.Path | None:
    """Extract font attachments into a private directory and return it.

    ``generation`` is the caller's opaque session token; it keeps concurrent
    sessions' font directories distinct. Returns ``None`` when the source has
    no usable font attachments. The caller owns the returned directory and is
    responsible for removing it when the session ends.
    """
    attachments = list_fonts(source)
    if not attachments:
        return None
    directory = parent / f"fonts-{generation}"
    try:
        cache_privacy.ensure_private_directory(directory)
    except OSError:
        return None
    extracted = 0
    for attachment in attachments:
        destination = directory / f"font-{attachment.index}{attachment.suffix}"
        if _extract_one(source, attachment, destination):
            extracted += 1
    if not extracted:
        _remove_directory(directory)
        return None
    return directory


def _remove_directory(directory: pathlib.Path) -> None:
    try:
        for child in directory.iterdir():
            child.unlink(missing_ok=True)
        directory.rmdir()
    except OSError:
        pass


def cleanup_fonts(directory: pathlib.Path | None) -> None:
    """Remove a directory returned by :func:`prepare_fonts`."""
    if directory is not None:
        _remove_directory(directory)
